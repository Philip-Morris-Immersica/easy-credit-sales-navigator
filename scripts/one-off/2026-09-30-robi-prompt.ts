function once(text: string, anchor: string, what: string): number {
  const first = text.indexOf(anchor);
  if (first < 0 || text.indexOf(anchor, first + 1) >= 0) throw new Error(`${what}: анкерът не е уникален/намерен`);
  return first;
}

function transform(prompt: string): string {
  let p = prompt.replace(/\r\n/g, "\n");
  if (p.includes("ТВЪРДИ ПРАВИЛА")) throw new Error("Промптът вече е обновен (има „ТВЪРДИ ПРАВИЛА“)");

  // 3) замяна на последния абзац (до края)
  const tailIdx = once(p, "Имаш достъп до и виждаш:", "финален абзац");
  p = p.slice(0, tailIdx) + REAL_ACCESS + "\n";

  // 2) блок „кой кого се обажда" преди РАЗЛИКА
  const diffIdx = once(p, "РАЗЛИКА ОБАЖДАНЕ / СРЕЩА:", "РАЗЛИКА");
  p = p.slice(0, diffIdx) + CONTACT_MAP + p.slice(diffIdx);

  // 1) твърди правила преди „КАКВО ПРАВИШ:"
  const doIdx = once(p, "КАКВО ПРАВИШ:", "КАКВО ПРАВИШ");
  p = p.slice(0, doIdx) + HARD_RULES + p.slice(doIdx);

  return p;
}

async function main() {
  const bot = await db.select().from(bots).where(eq(bots.key, "consultant")).then((r) => r[0]);
  if (!bot) throw new Error("няма бот consultant");
  let base = bot.systemPrompt;
  if (REBUILD) {
    const first = await db
      .select()
      .from(botVersions)
      .where(and(eq(botVersions.botKey, "consultant"), eq(botVersions.reason, "initial")))
      .orderBy(asc(botVersions.changedAt))
      .limit(1)
      .then((r) => r[0]);
    if (!first) throw new Error("няма initial версия за --rebuild");
    base = first.systemPrompt;
  }
  const next = transform(base);
  writeFileSync("_audit_tmp/robi-prompt-after.txt", next, "utf8");
  console.log(`systemPrompt: ${bot.systemPrompt.length} -> ${next.length} знака`);
  if (DRY) {
    console.log("DRY RUN — нищо не е записано. Резултат: _audit_tmp/robi-prompt-after.txt");
  } else {
    await snapshotBot(bot, null, "script");
    await db.update(bots).set({ systemPrompt: next, updatedAt: new Date() }).where(eq(bots.key, "consultant"));
    console.log("Записано.");
  }
  process.exit(0);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});

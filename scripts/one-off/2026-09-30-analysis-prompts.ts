function once(text: string, re: RegExp, replace: (m: RegExpMatchArray) => string, what: string): string {
  const matches = [...text.matchAll(new RegExp(re.source, re.flags.includes("g") ? re.flags : re.flags + "g"))];
  if (matches.length !== 1) throw new Error(`${what}: очаквах 1 съвпадение, има ${matches.length}`);
  const m = matches[0];
  return text.slice(0, m.index!) + replace(m) + text.slice(m.index! + m[0].length);
}

function transform(key: string, prompt: string): string {
  let p = prompt;

  // 1) фокус (само за изостаналите пет)
  if (NEW_FOCUS[key]) {
    p = once(p, /ФОКУС НА СЦЕНАРИЯ:[^\r\n]*/, () => NEW_FOCUS[key], `${key} фокус`);
  }

  // 2) шести критерий — след реда „Затваряне на сделката"
  if (p.includes("Продажбен резултат")) throw new Error(`${key}: вече има „Продажбен резултат"`);
  p = once(
    p,
    /^([ \t]*\{ "name": "Затваряне на сделката".*)$/m,
    (m) => `${m[1]},\n${m[1].replace("Затваряне на сделката", "Продажбен резултат")}`,
    `${key} критерий`
  );

  // 3) примери от разговора в силните страни и подобренията
  p = once(
    p,
    /^([ \t]*)"strengths":.*$/m,
    (m) => `${m[1]}"strengths": ["<сила 1 — на „ти“, с конкретен пример от разговора>", "<сила 2 — на „ти“, с конкретен пример от разговора>"],`,
    `${key} strengths`
  );
  p = once(
    p,
    /^([ \t]*)"improvements":.*$/m,
    (m) =>
      `${m[1]}"improvements": ["<подобрение 1 — на „ти“: какво точно се е случило в разговора (с реалната реплика), защо е проблем и по-добра реплика>", "<подобрение 2 — на „ти“, по същия начин>"],`,
    `${key} improvements`
  );

  return p;
}

async function main() {
  mkdirSync("_audit_tmp", { recursive: true });
  let dump = "";
  for (const key of KEYS) {
    const bot = await db.select().from(bots).where(eq(bots.key, key)).then((r) => r[0]);
    if (!bot?.analysisPrompt) throw new Error(`${key}: няма analysisPrompt`);
    const next = transform(key, bot.analysisPrompt);
    dump += `\n########## ${key}\n${next}\n`;
    console.log(`${key.padEnd(32)} ${bot.analysisPrompt.length} -> ${next.length} знака`);

    if (!DRY) {
      await snapshotBot(bot, null, "script");
      await db
        .update(bots)
        .set({ analysisPrompt: next, analysisMaxTokens: NEW_MAX_TOKENS, updatedAt: new Date() })
        .where(eq(bots.key, key));
    }
  }
  writeFileSync("_audit_tmp/analysis-prompts-after.txt", dump, "utf8");
  console.log(DRY ? "\nDRY RUN — нищо не е записано. Резултат: _audit_tmp/analysis-prompts-after.txt" : "\nЗаписано.");
  process.exit(0);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});

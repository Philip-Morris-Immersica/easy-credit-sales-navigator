import { writeFileSync, mkdirSync } from "fs";
import path from "path";
import { Document, HeadingLevel, Packer, Paragraph, TextRun } from "docx";

type Item =
  | { h: string }
  | { p: string }
  | { b: string[] }
  | { meta: [string, string][] };

function build(items: Item[]): Document {
  const children: Paragraph[] = [];
  for (const it of items) {
    if ("meta" in it) {
      for (const [k, v] of it.meta) {
        children.push(
          new Paragraph({ children: [new TextRun({ text: `${k}: `, bold: true }), new TextRun(v)] })
        );
      }
      children.push(new Paragraph(""));
    } else if ("h" in it) {
      children.push(new Paragraph({ text: it.h, heading: HeadingLevel.HEADING_2 }));
    } else if ("p" in it) {
      children.push(new Paragraph({ text: it.p, spacing: { after: 120 } }));
    } else {
      for (const line of it.b) children.push(new Paragraph({ text: line, bullet: { level: 0 } }));
    }
  }
  return new Document({ sections: [{ children }] });
}


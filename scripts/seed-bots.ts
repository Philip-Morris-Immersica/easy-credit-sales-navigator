async function main() {
  console.log("Seeding bots...");
  for (const bot of botsData) {
    const existing = await db
      .select({ id: schema.bots.id })
      .from(schema.bots)
      .where(eq(schema.bots.key, bot.key))
      .then((r) => r[0]);

    if (existing) {
      await db.update(schema.bots).set(bot).where(eq(schema.bots.key, bot.key));
      console.log(`  Updated bot: ${bot.key}`);
    } else {
      await db.insert(schema.bots).values(bot);
      console.log(`  Created bot: ${bot.key}`);
    }
  }

  console.log("Seeding model pricing...");
  for (const p of pricingData) {
    const existing = await db
      .select({ model: schema.modelPricing.model })
      .from(schema.modelPricing)
      .where(eq(schema.modelPricing.model, p.model))
      .then((r) => r[0]);

    if (existing) {
      await db.update(schema.modelPricing).set(p).where(eq(schema.modelPricing.model, p.model));
    } else {
      await db.insert(schema.modelPricing).values(p);
    }
    console.log(`  Priced: ${p.model}`);
  }

  console.log("\nSeed complete!");
  process.exit(0);
}

